#!/usr/bin/env node
// Asset build: assets/source/*.bbmodel -> public/assets/models/*.glb, then merges
// converter output (clip lengths, loop modes, sockets, root motion, colliders)
// with assets/manifest.authored.json (hit windows, events, props) into
// public/assets/asset_manifest.json. Fails on any authored reference that does
// not exist in the source art, so timing data cannot silently drift.
import { mkdirSync, readFileSync, renameSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FPS, MODELS, SCALE } from './asset-config.mjs';
import { convertBBModel } from './lib/convert.mjs';
import { validateAuthored } from './lib/validate.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = join(root, 'assets/source');
const outDir = join(root, 'public/assets');
mkdirSync(join(outDir, 'models'), { recursive: true });

// Write-then-rename so a dev server never serves a half-written file.
const writeAtomic = (path, data) => {
  writeFileSync(`${path}.tmp`, data);
  renameSync(`${path}.tmp`, path);
};

const started = performance.now();
const models = {};
let warningCount = 0;

for (const spec of MODELS) {
  const bb = JSON.parse(readFileSync(join(sourceDir, spec.source), 'utf8'));
  const { glb, meta, warnings } = convertBBModel(bb, {
    scale: SCALE,
    fps: FPS,
    materials: spec.materials ?? [],
    colliders: spec.colliders,
  });
  const file = `models/${spec.id}.glb`;
  writeAtomic(join(outDir, file), glb);
  models[spec.id] = { file, ...meta };
  for (const w of warnings) console.warn(`  ! ${spec.id}: ${w}`);
  warningCount += warnings.length;
  console.log(`  ${spec.id.padEnd(16)} ${(glb.byteLength / 1024).toFixed(0).padStart(5)} KB  ${Object.keys(meta.clips).length} clips  sockets: ${meta.sockets.join(', ') || '-'}`);
}

const authored = JSON.parse(readFileSync(join(root, 'assets/manifest.authored.json'), 'utf8'));
const errors = validateAuthored(authored, models);
if (errors.length) {
  console.error(`\nmanifest.authored.json has ${errors.length} error(s):`);
  for (const e of errors) console.error(`  x ${e}`);
  process.exit(1);
}

// Merge authored timing into the generated clip entries.
for (const [modelId, clips] of Object.entries(authored.models)) {
  for (const [clipName, data] of Object.entries(clips)) {
    const clip = models[modelId].clips[clipName];
    clip.hits = data.hits ?? [];
    clip.events = (data.events ?? []).slice().sort((a, b) => a.t - b.t);
    if (data.cancelAt !== undefined) clip.cancelAt = data.cancelAt;
    const props = new Set(clip.events.filter((e) => e.prop).map((e) => e.prop));
    if (props.size) clip.props = [...props];
  }
}

const manifest = {
  version: 1,
  $comment: 'GENERATED by tools/build-assets.mjs. Edit assets/source/*.bbmodel or assets/manifest.authored.json instead.',
  units: 'meters; Blockbench px / 16. Models face -Z.',
  props: authored.props,
  models,
};
writeAtomic(join(outDir, 'asset_manifest.json'), JSON.stringify(manifest, null, 1));
console.log(`\nWrote ${MODELS.length} models + asset_manifest.json in ${(performance.now() - started).toFixed(0)} ms` + (warningCount ? ` (${warningCount} warnings)` : ''));
